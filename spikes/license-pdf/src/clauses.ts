/** 标点压在行宽边界上：每一小句的长度在 43 到 49 个字之间变化，让逗号、句号轮流落到行尾附近 */
const boundaryPunctuation = Array.from({ length: 14 }, (_, index) => {
  const length = 43 + (index % 7);
  const filler =
    "本句长度逐句变化以便让句末标点依次落在每一行的末尾与下一行的开头附近看它会不会跑到行首去";
  const body = `第${String(index + 1).padStart(2, "0")}句`.concat(filler).slice(0, length - 1);
  return body + (index % 2 === 0 ? "，" : "。");
}).join("");

