const registry: Record<string, Clause> = { ...v1, ...s1, ...x1 };

export function clauseFor(key: string): Clause {
  const clause = registry[key];
  if (clause === undefined) throw new Error(`没有这个条款键：${key}`);
  return clause;
}

export function clauseKeys(): string[] {
  return Object.keys(registry);
}
