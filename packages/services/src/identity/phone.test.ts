// 手机号的区号判断（不连库）。连库的一条在 identity.db.test.ts：带 +1 的号码登不进数字相同的大陆号的账号。
import { describe, expect, it } from "vitest";

import { normalizePhone } from "../security/index.js";
import { mainlandMobileOf } from "./phone.js";

describe("mainlandMobileOf", () => {
  it.each([
    "13125550199",
    "131 2555 0199",
    "131-2555-0199",
    "+8613125550199",
    "+86 131 2555 0199",
    "(+86) 131-2555-0199",
    "008613125550199",
    "0086 131 2555 0199",
    "8613125550199",
  ])("大陆号 %s：给出 11 位数字，与盲索引的归一化一致", (raw) => {
    expect(mainlandMobileOf(raw)).toBe("13125550199");
    expect(normalizePhone(raw)).toBe("13125550199");
  });

  it.each([
    // 去掉符号后正好是“1 开头的 11 位”的北美号码：复审里登进别人账号的三种写法，加 00 前缀的一种
    "+13125550199",
    "+1 312 555 0199",
    "+1 (312) 555-0199",
    "0013125550199",
    "001 312 555 0199",
    // 别的区号
    "+85291234567",
    "+44 7911 123456",
    "+886 912 345 678",
    // 加号不是半角的、前面带别的字符的：认不出的写法不猜
    "＋13125550199",
    "tel:13125550199",
    // 86 后面不是大陆手机号
    "+86 21 5555 0199",
    "+86 131 2555 019",
    // 位数不对、不以 1 开头、空串
    "1312555019",
    "131255501990",
    "23125550199",
    "",
  ])("不认 %s", (raw) => {
    expect(mainlandMobileOf(raw)).toBeNull();
  });
});
